#!/usr/bin/env python3
"""Build an acquisition manifest for original-source candidate datasets."""

from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path
from typing import Any


PROJECT_ROOT = Path(__file__).resolve().parents[2]
DEFAULT_CONFIG = Path("configs/dataset_acquisition_registry_v1.json")


def resolve_path(value: str | Path) -> Path:
    path = Path(value)
    return path if path.is_absolute() else PROJECT_ROOT / path


def load_config(path: Path) -> dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8"))


def action_command(action: dict[str, Any]) -> str:
    kind = str(action.get("action", ""))
    if kind == "geo_supplementary":
        config_path = action["config_path"]
        return f"pixi run --environment core python scripts/download/geo_supplementary.py --config {config_path}"
    if kind == "sra_runinfo":
        url = action["url"]
        accession = action.get("series_accession", "sra")
        return f"curl -L --fail --output reports/dataset_acquisition/{accession}_SraRunInfo.csv '{url}'"
    if kind == "custom_script":
        return str(action["command"])
    if kind == "manual_author_figshare":
        return f"# manual: open {action['url']}"
    return "# no command registered"


def build_rows(config: dict[str, Any]) -> list[dict[str, str]]:
    rows: list[dict[str, str]] = []
    for dataset in config["datasets"]:
        local_paths = [resolve_path(p) for p in dataset.get("local_paths", [])]
        existing_paths = [str(p.relative_to(PROJECT_ROOT)) for p in local_paths if p.exists()]
        all_local_present = bool(local_paths) and all(p.exists() for p in local_paths)
        for action in dataset.get("download_actions", []):
            rows.append(
                {
                    "dataset_id": str(dataset["dataset_id"]),
                    "display_name": str(dataset["display_name"]),
                    "priority": str(dataset["priority"]),
                    "role": str(dataset["role"]),
                    "official_source_type": str(dataset["official_source_type"]),
                    "official_accession": str(dataset["official_accession"]),
                    "readout_day": str(dataset["readout_day"]),
                    "source_preference": str(dataset["source_preference"]),
                    "local_status": "complete" if all_local_present else ("partial" if existing_paths else "missing"),
                    "existing_local_paths": ";".join(existing_paths),
                    "action": str(action.get("action", "")),
                    "command": action_command(action),
                    "note": str(action.get("note", "")),
                }
            )
    return rows


def write_tsv(rows: list[dict[str, str]], path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if not rows:
        path.write_text("", encoding="utf-8")
        return
    with path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0].keys()), delimiter="\t")
        writer.writeheader()
        writer.writerows(rows)


def write_download_plan(rows: list[dict[str, str]], path: Path, *, missing_only: bool) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "#!/usr/bin/env bash",
        "set -euo pipefail",
        "",
        "# Generated by scripts/download/build_dataset_acquisition_manifest.py",
        "# Review commands before running. Large GEO/SRA downloads can be expensive.",
        "",
    ]
    for row in rows:
        if missing_only and row["local_status"] == "complete":
            continue
        lines.append(f"# {row['priority']} {row['dataset_id']} | {row['display_name']}")
        lines.append(f"# role: {row['role']} | source: {row['official_source_type']} {row['official_accession']}")
        if row["note"]:
            lines.append(f"# note: {row['note']}")
        lines.append(row["command"])
        lines.append("")
    path.write_text("\n".join(lines), encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description="Build original-source dataset acquisition manifest.")
    parser.add_argument("--config", default=str(DEFAULT_CONFIG), help="Dataset acquisition config JSON")
    parser.add_argument("--include-complete", action="store_true", help="Include already-complete datasets in download plan")
    args = parser.parse_args()

    config_path = resolve_path(args.config)
    config = load_config(config_path)
    rows = build_rows(config)
    manifest_path = resolve_path(config["acquisition_manifest_path"])
    plan_path = resolve_path(config["download_plan_path"])
    write_tsv(rows, manifest_path)
    write_download_plan(rows, plan_path, missing_only=not args.include_complete)
    print(f"wrote {manifest_path.relative_to(PROJECT_ROOT)}\t{len(rows)} rows")
    print(f"wrote {plan_path.relative_to(PROJECT_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
